#!/usr/bin/env python3
"""Builds supabase/migrations/20261127000004_prompts.sql from prompts.py.

Run:  python3 supabase/prompts/build.py
Each prompt lists its valid answers most-common first; that order seeds the
starting rarity until real player answers take over.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from prompts import PROMPTS  # noqa: E402

ROMAN = {"I": 1, "II": 2, "III": 3, "IV": 4, "V": 5, "VI": 6, "VII": 7, "VIII": 8}
ORD = {1: "First", 2: "Second", 3: "Third", 4: "Fourth", 5: "Fifth", 6: "Sixth", 7: "Seventh", 8: "Eighth"}


def roman_aliases(name):
    """'Henry VIII' -> ['Henry 8', 'Henry the Eighth']."""
    parts = name.split(" ")
    if len(parts) == 2 and parts[1] in ROMAN:
        n = ROMAN[parts[1]]
        return [f"{parts[0]} {n}", f"{parts[0]} the {ORD[n]}"]
    return []


def q(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    out = [
        "-- =====================================================================",
        "-- Tenfold: launch prompts for rare-answer mode (generated by",
        "-- supabase/prompts/build.py, edit prompts.py and rebuild).",
        "-- Answers are listed most-common first: that order seeds rarity.",
        "-- =====================================================================",
        "",
    ]
    seen = set()
    for p in PROMPTS:
        cat, diff, pool, prompt, note, answers = p
        assert prompt not in seen, prompt
        seen.add(prompt)
        items = []
        for raw in answers.split(";"):
            raw = " ".join(raw.split())
            if not raw:
                continue
            names = [x.strip() for x in raw.split("|") if x.strip()]
            names += [a for a in roman_aliases(names[0]) if a not in names]
            items.append("|".join(names))
        assert len(items) >= 3, prompt
        out.append(
            "select public.seed_prompt({}, {}, {}, {}, {}, array[\n  {}\n]);".format(
                q(cat), diff, q(pool), q(prompt), q(note) if note else "null",
                ",\n  ".join(q(i) for i in items),
            )
        )
        out.append("")
    path = os.path.join(os.path.dirname(__file__), "..", "migrations", "20261127000004_prompts.sql")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print(f"{len(PROMPTS)} prompts, {sum(len(p[5].split(';')) for p in PROMPTS)} answers -> {os.path.normpath(path)}")


if __name__ == "__main__":
    main()
